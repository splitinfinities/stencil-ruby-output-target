import type { ComponentModel, PropModel } from './model.ts';
import type { ResolvedOptions } from './options.ts';
import { rubyString, snake } from './naming.ts';

const HEADER = '# frozen_string_literal: true\n\n# Generated by stencil-ruby-output-target. Do not edit.\n';

function openModules(namespace: string) {
  const parts = namespace.split('::');

  return {
    open: parts.map((part, i) => `${'  '.repeat(i)}module ${part}`).join('\n'),
    close: parts.map((_, i) => `${'  '.repeat(parts.length - 1 - i)}end`).join('\n'),
    indent: '  '.repeat(parts.length),
  };
}

function propLine(prop: PropModel) {
  const args = [
    `:${prop.key}`,
    `type: :${prop.kind}`,
    `js: ${rubyString(prop.jsName)}`,
    prop.attribute ? `attribute: ${rubyString(prop.attribute)}` : null,
    prop.values ? `values: %w[${prop.values.join(' ')}].freeze` : null,
    prop.rubyDefault !== null && prop.rubyDefault !== 'nil' ? `default: ${prop.rubyDefault}` : null,
    `strategy: :${prop.strategy}`,
    prop.reader !== prop.key ? `reader: :${prop.reader}` : null,
    prop.required ? 'required: true' : null,
    prop.list ? 'list: true' : null,
    prop.reactive ? 'reactive: true' : null,
  ].filter(Boolean);

  return `prop ${args.join(', ')}`;
}

export function emitComponentClass(component: ComponentModel, options: ResolvedOptions) {
  const { open, close, indent } = openModules(options.rubyNamespace);
  const i = (line: string) => (line ? `${indent}  ${line}` : '');
  const lines: string[] = [];

  lines.push(`self.element_tag = ${rubyString(component.tag)}`);

  if (component.model) {
    lines.push(`self.model = {prop: ${rubyString(component.model.prop)}, event: ${rubyString(component.model.event)}}.freeze`);
  }

  if (component.formField) {
    const entries = Object.entries(component.formField).map(([key, js]) => `${snake(key)}: :${snake(js)}`);
    lines.push(`self.form_field = {${entries.join(', ')}}.freeze`);
  }

  if (component.props.length) lines.push('');

  for (const prop of component.props) lines.push(propLine(prop));

  if (component.events.length) {
    lines.push('');

    for (const event of component.events) lines.push(`event :${event.key}, dom: ${rubyString(event.dom)}`);
  }

  const named = component.slots.filter((s) => s.name !== '');

  if (named.length) {
    lines.push('');

    for (const slot of named) lines.push(`${slot.many ? 'renders_many' : 'renders_one'} :${slot.rubyName}`);
  }

  // The class's doc comment, at the class's own indentation.
  const docs = component.docs ? component.docs.split('\n').map((l) => `${indent}# ${l}`.trimEnd()) : [];

  return `${HEADER}
${open}
${docs.length ? `${docs.join('\n')}\n` : ''}${indent}# Renders <${component.tag}>. Helper: ${component.helper}(...)
${indent}class ${component.className} < BaseComponent
${lines.map(i).join('\n')}
${indent}end
${close}
`;
}

export function emitHelpers(components: ComponentModel[], options: ResolvedOptions) {
  const { open, close, indent } = openModules(options.rubyNamespace);

  const hook = `${options.configKey}_render`;

  const methods = components
    .map((c) => `${indent}  def ${c.helper}(*args, **kwargs, &block)\n${indent}    ${hook}(${c.className}.new(*args, **kwargs), &block)\n${indent}  end`)
    .join('\n\n');

  // How a helper renders: ActionView's render in Rails; elsewhere the component renders itself
  // in the caller's view (ForeignContext takes it from there).
  const render = {
    rails: 'render(component, &)',
    sinatra: 'component.render_in(self, &)',
    bridgetown: 'component.render_in(view, &)',
  }[options.framework];

  return `${HEADER}
${open}
${indent}# One helper per element. ${options.framework === 'rails' ? 'The engine includes it in every view.' : `The ${options.framework} adapter adds it to your templates.`}
${indent}module Helpers
${indent}  # Renders a component where the helpers are used.
${indent}  def ${hook}(component, &)
${indent}    ${render}
${indent}  end

${methods}
${indent}end
${close}
`;
}

/** The runtime half of the DSL that the generated classes call. Static, emitted once. */
export function emitBaseComponent(options: ResolvedOptions) {
  const { open, close, indent } = openModules(options.rubyNamespace);

  const body = String.raw`
# Shared behaviour for every generated element component. Props are declared with "prop",
# which declares each as an OptStruct option, the way the Rails gem's components declare
# theirs; anything else passed to "new" is forwarded onto the host element.
class BaseComponent < ViewComponent::Base
  include OptStruct.build

  class_attribute :element_tag, instance_writer: false
  class_attribute :model, instance_writer: false, default: nil
  class_attribute :props, instance_writer: false, default: {}.freeze
  class_attribute :events, instance_writer: false, default: {}.freeze
  # Form-associated elements only: { value: :value, checked: :checked, checked_value: :value,
  # label: :label, error: :error }, the props a form field fills in.
  class_attribute :form_field, instance_writer: false, default: nil

  # Methods the generated template and ViewComponent itself call. Other ActionView
  # helpers (label, select, …) may be shadowed: slot blocks run in the caller's view.
  # OptStruct's own instance methods (fetch, defaults) hold the options.
  PROTECTED_OWNERS = [
    ActionView::Helpers::TagHelper, ActionView::Helpers::CaptureHelper,
    ActionView::Helpers::OutputSafetyHelper, ActionView::Helpers::RenderingHelper,
    OptStruct::InstanceMethods
  ].freeze

  # The hash attributes Rails writes as one attribute per key (data: { x: 1 } is data-x="1").
  NESTED_ATTRIBUTES = %w[data aria].freeze

  # How Rails' date and time fields write a value, by input type (or picker).
  TIME_FORMATS = {
    "date" => "%Y-%m-%d", "time" => "%H:%M", "datetime-local" => "%Y-%m-%dT%H:%M",
    "month" => "%Y-%m", "week" => "%G-W%V"
  }.freeze

  # reactive: the partial flavor renders it so it follows server state on a reactive page
  # (reactive_value, and data-stencil-attributes for a boolean). The component ignores it.
  def self.prop(key, type:, js:, strategy:, attribute: nil, values: nil, default: nil, reader: key, required: false, list: false, reactive: false)
    if method_defined?(reader) || private_method_defined?(reader)
      owner = instance_method(reader).owner
      if owner == BaseComponent || owner.name.to_s.start_with?("ViewComponent") || PROTECTED_OWNERS.include?(owner)
        raise ArgumentError, "#{name}: prop reader #{reader.inspect} would replace #{owner}##{reader}; pass a different reader:"
      end
    end
    self.props = props.merge(key => {type:, js:, attribute:, values:, default:, strategy:, reader:, required:, list:, reactive:}.freeze).freeze
    (reader == key) ? declare_option(key, default, required) : declare_renamed_option(key, reader, default, required)
  end

  # The option, its default (a lambda, so OptStruct never reads a value as a method name) and
  # whether it's required, with OptStruct's reader. Its writer stays private: the caller's
  # value is validated once, in initialize.
  def self.declare_option(key, default, required)
    option(key, default: -> { default }, required:)
    private :"#{key}="
  end
  private_class_method :declare_option

  # OptStruct names an option's reader after its key, and this key's reader would replace a
  # method the component needs (tag, content, open, …). OptStruct still owns the key, its
  # default and whether it's required; the reader is defined here under its own name.
  def self.declare_renamed_option(key, reader, default, required)
    defined_keys << key
    defaults[key] = -> { default }
    required_keys << key if required
    define_method(reader) { options[key] }
  end
  private_class_method :declare_renamed_option

  def self.event(key, dom:)
    self.events = events.merge(key => dom).freeze
  end

  # The Rails form field for a form-associated element, derived as the gem's form:
  # and attribute: options derive it. Options the caller passes win.
  #   name   form.field_name(attribute)       user[email]
  #   id     form.field_id(attribute)         user_email
  #   value  the object's value; checked state for a checkbox, radio or switch
  #   error  the attribute's first full error message
  #   label  the attribute's human name
  #   required  an unconditional presence validator
  # Without a form, name and id are the attribute itself.
  def self.form_options(form, attribute, options = {})
    raise ArgumentError, "#{name} (<#{element_tag}>) is not a form control" unless form_field

    options = options.dup
    object = form.respond_to?(:object) ? form.object : nil
    options[:name] = form ? form.field_name(attribute) : attribute.to_s unless options.key?(:name)
    options[:id] = form ? form.field_id(attribute) : attribute.to_s unless options.key?(:id)
    label = form_field[:label]
    options[label] = human_attribute_name(object, attribute) if label && !options.key?(label)
    options[:required] = true if props.key?(:required) && !options.key?(:required) && required_attribute?(object, attribute)
    error = form_field[:error]
    if error && !options.key?(error) && object.respond_to?(:errors)
      message = object.errors.full_messages_for(attribute).first
      options[error] = message if message
    end
    return options unless object.respond_to?(attribute)

    raw = object.public_send(attribute)
    if checkable?(options)
      # What it submits while checked; Rails' check_box default is "1".
      on = options.fetch(form_field[:checked_value]) { props.dig(form_field[:checked_value], :default) }.presence || "1"
      radio = radio?(options)
      options[form_field[:checked]] = checked_value?(raw, on, radio) unless options.key?(form_field[:checked])
      # Rails' check_box submits "0" while unchecked, from a hidden field.
      options[:unchecked_value] = "0" if props.key?(:unchecked_value) && !radio && !options.key?(:unchecked_value)
    elsif form_field[:value] && !options.key?(form_field[:value])
      value = form_value(raw, options[:type] || element_tag.delete_prefix(${rubyString(options.tagPrefix)}).delete_suffix("-picker"))
      options[form_field[:value]] = value unless value.nil?
    end
    options
  end

  # An unconditional presence validator (ActiveModel's validates :x, presence: true) makes the
  # field required.
  def self.required_attribute?(object, attribute)
    return false unless object.class.respond_to?(:validators_on)

    object.class.validators_on(attribute).any? { |validator| validator.kind == :presence && validator.options.slice(:if, :unless, :on).empty? }
  end

  def self.human_attribute_name(object, attribute)
    klass = object&.class
    klass.respond_to?(:human_attribute_name) ? klass.human_attribute_name(attribute) : attribute.to_s.humanize
  end

  # A control with a checked prop is checkable, unless it has a type that says otherwise
  # (an input is a checkbox only as type: "checkbox" or "radio").
  def self.checkable?(options)
    return false unless form_field[:checked]

    !props.key?(:type) || %w[checkbox radio].include?(options[:type].to_s)
  end

  # A radio by its type or its as.
  def self.radio?(options)
    %i[type as].any? { |key| props.key?(key) && options[key].to_s == "radio" }
  end

  # Rails' CheckBox#checked? and RadioButton#checked?.
  def self.checked_value?(raw, on, radio)
    return raw.to_s == on.to_s if radio

    case raw
    when TrueClass, FalseClass then raw
    when NilClass then false
    when String then raw == on.to_s
    when Array then raw.map(&:to_s).include?(on.to_s)
    else raw.to_i == on.to_i
    end
  end

  # Plain values only: an attachment or another object has no attribute form.
  def self.form_value(raw, kind)
    case raw
    when String, Numeric, TrueClass, FalseClass then raw
    when Symbol then raw.to_s
    when Array then raw.map { |item| item.is_a?(Hash) ? item : item.to_s }
    when Date, Time
      format = TIME_FORMATS[kind.to_s]
      format ? raw.strftime(format) : raw.iso8601
    else
      (raw.respond_to?(:to_time) && raw.respond_to?(:strftime)) ? form_value(raw.to_time, kind) : nil
    end
  end

  # bind:  name of a server state (ReActionView/Herb state.set) the model event writes.
  # state: name of a client-declared herb:state the model event writes, no round trip
  #        (data-herb-set="update->name=$value", Herb's own action). An element with a state
  #        prop (badge, button: the status color) keeps state: for the prop and takes this as
  #        client_state:.
  # form:, attribute: (form controls) name the field the Rails way; see form_options.
  #
  # Props the caller doesn't pass take the configured defaults (config.defaults[:key]) first.
  # OptStruct keeps every keyword in options, fills in the props' defaults and raises for a
  # missing required prop; the props are then validated in place, and the rest of options is
  # the host's attributes (html_attributes).
  def initialize(**kwargs)
    kwargs = ${options.rubyNamespace}.config.defaults.for_class(self.class).merge(kwargs)
    bind = kwargs.delete(:bind) unless props.key?(:bind)
    state = kwargs.delete(props.key?(:state) ? :client_state : :state)
    if form_field && kwargs.key?(:attribute)
      attribute = kwargs.delete(:attribute)
      kwargs = self.class.form_options(kwargs.delete(:form), attribute, kwargs)
    end
    @provided = props.keys.select { |key| kwargs.key?(key) }
    # OptStruct's initialize, given kwargs as they are now.
    super
    @lists = {}
    props.each do |key, spec|
      value = options[key]
      raise ArgumentError, "#{self.class.name} requires #{key}:" if spec[:required] && value.nil?

      # A list for a string attribute: JSON in the attribute, the list itself as a property.
      if spec[:list] && value.is_a?(Array)
        @lists[spec[:js]] = value
        value = value.to_json
      end

      options[key] = __stencil_checked(key, spec, value)
    end
    @__stencil_bind = bind
    @__stencil_state = state
  end

  # Records the element for the head's preloads (config.assets.async; see Assets).
  def render_in(view_context, &)
    ${options.rubyNamespace}::Assets.current.record(element_tag) if ${options.rubyNamespace}.config.assets.async
    super
  end

  # Whether a prop's attribute renders. A value prop always; an optional one only when the
  # caller gave it (and not as its default). A boolean the HTML way: present when on, never
  # "false" for one that defaults to false (a form-associated element reads any value as true,
  # as a native control does, and :host([x]) selectors match it); a boolean that defaults to
  # true is turned off with "false". Public, so the partial flavor can ask the component.
  def attribute?(key)
    spec = props.fetch(key)
    value = public_send(spec[:reader])
    return false if spec[:strategy] == :optional && @provided.exclude?(key) && value == spec[:default]
    return value ? true : spec[:default] == true if spec[:type] == :boolean

    !value.nil?
  end

  # The value attribute?(key) renders: "" for a boolean that's on, "false" for one turned off.
  def attribute_value(key)
    spec = props.fetch(key)
    value = public_send(spec[:reader])
    return (value ? "" : "false") if spec[:type] == :boolean

    value.to_s
  end

  # A reactive prop's value slot in the partial flavor: rendered whether or not the caller gave
  # it, so Herb has an attribute to rewrite on a reply (it can't add one, spike S2). Unset (nil)
  # is the default, or "", which the default reactive props read as unset.
  def reactive_value(key)
    spec = props.fetch(key)
    value = public_send(spec[:reader])
    (value.nil? ? spec[:default] : value).to_s
  end

  # Caller attributes plus the reactive wiring, merged the way Rails merges data/aria hashes,
  # for tag.attributes: the one ERB output Herb allows in attribute position.
  def host_attributes
    data = (html_attributes[:data] || {}).dup
    if model
      data[:stencil_set] = "#{model[:event]}->#{@__stencil_bind}" if @__stencil_bind
      data[:herb_set] = herb_set if herb_set.present?
      data[:stencil_state] = client_binding if client_binding.present?
    end
    html_attributes.merge(data:)
  end

  # The partial flavor's host attributes, each a value slot Herb rewrites in place. An ERB
  # output in attribute position (tag.attributes(...) with a hash) is an "element" slot, which
  # Herb's client (0.11) writes as content in place of the element, so the partial has none:
  # id and class go out as themselves, the bindings as their attributes, and anything else as
  # JSON in data-stencil-attributes, which the bridge sets.
  def host_id
    html_attributes[:id].to_s
  end

  def host_class
    value = html_attributes[:class]
    value = value.select { |_, on| on }.keys if value.is_a?(Hash)
    Array(value).flatten.compact.join(" ")
  end

  def server_binding
    (model && @__stencil_bind) ? "#{model[:event]}->#{@__stencil_bind}" : ""
  end

  # state: for an element whose model is its value, Herb's own action grammar, which reads a
  # custom element's .value on its custom event (spike S6), so the write needs no bridge.
  def herb_set
    (model && @__stencil_state && model[:prop] == "value") ? "#{model[:event]}->#{@__stencil_state}=$value" : ""
  end

  # state: for any other model, through the bridge's data-stencil-state.
  def client_binding
    (model && @__stencil_state && model[:prop] != "value") ? "#{model[:event]}->#{@__stencil_state}" : ""
  end

  # Reactive booleans are listed here too, while on: Herb can't add or remove an attribute
  # (spike S2), but it rewrites this one, and the bridge then sets or removes theirs, which
  # Stencil turns into the property.
  def host_attribute_payload
    payload = html_attributes.except(:id, :class).each_with_object({}) do |(key, value), out|
      if NESTED_ATTRIBUTES.include?(key.to_s) && value.is_a?(Hash)
        value.each do |name, item|
          out["#{key}-#{name.to_s.dasherize}"] = (item.is_a?(String) || item.is_a?(Symbol)) ? item.to_s : item.to_json unless item.nil?
        end
      elsif !value.nil? && value != false
        out[key.to_s] = (value == true) ? "" : value.to_s
      end
    end
    props.each do |key, spec|
      payload[spec[:attribute]] = attribute_value(key) if spec[:reactive] && spec[:type] == :boolean && attribute?(key)
    end
    payload.to_json
  end

  # JSON for props without an attribute (strategy :property), and lists given for
  # string attributes. The TS runtime assigns them.
  def property_payload
    props.each_with_object(@lists.dup) do |(key, spec), payload|
      next unless spec[:strategy] == :property

      value = public_send(spec[:reader])
      payload[spec[:js]] = value unless value.nil?
    end.to_json
  end

  # Named slot content with slot="name" on each of its top-level elements, so the element is
  # assigned what the caller wrote (each panel of a tab set, a nav's center
  # button), not a wrapper. Text outside any element gets a span of its own.
  def slotted(name, html)
    fragment = Nokogiri::HTML5.fragment(html.to_s)
    fragment.children.each do |node|
      if node.element?
        node["slot"] = name
      elsif node.text? && node.content.strip.empty?
        node.remove
      elsif node.text?
        span = fragment.document.create_element("span", slot: name, style: "display: contents")
        node.add_next_sibling(span)
        span.add_child(node)
      end
    end
    # The caller's content, already rendered (and escaped) by its view; only slot= was added.
    fragment.to_html.html_safe # rubocop:disable Rails/OutputSafety -- see above
  end

  private

  # What the caller passed besides the props (and bind:, state:, form:, attribute:).
  def html_attributes
    options.except(*self.class.defined_keys)
  end

  def __stencil_checked(key, spec, value)
    return value if value.nil? || spec[:values].nil? || spec[:values].include?(value.to_s)

    # Raises in development and test; logs otherwise, and the prop keeps its default.
    ${options.rubyNamespace}.config.invalid!("#{self.class.name} #{key}: #{value.inspect} is not one of #{spec[:values].join(", ")}")
    spec[:default]
  end
end`;

  return `${HEADER}
# Slot content is parsed to set slot="…" on its elements; Rails loads Nokogiri anyway.
require "nokogiri"
# Props are OptStruct options (opt_struct, MIT; the gemspec's dependency).
require "opt_struct"

${open}
${body
  .trim()
  .split('\n')
  .map((line) => (line ? `${indent}${line}` : ''))
  .join('\n')}
${close}
`;
}
