import type { ResolvedOptions } from './options.ts';
import { namespacePath, rubyString } from './naming.ts';

/**
 * The gem's own code under lib/ and its gemspec: the entry point, the version, the bundle
 * helper, the Rails engine and the deprecated names. Everything is read from the options, so
 * another Stencil library that configures the target gets the same gem shape.
 */

export const HEADER = '# frozen_string_literal: true\n\n# Generated by stencil-ruby-output-target. Do not edit.\n';

export function openModules(namespace: string) {
  const parts = namespace.split('::');

  return {
    open: parts.map((part, i) => `${'  '.repeat(i)}module ${part}`).join('\n'),
    close: parts.map((_, i) => `${'  '.repeat(parts.length - 1 - i)}end`).join('\n'),
    indent: '  '.repeat(parts.length),
  };
}

/** Wraps a body (written at column 0) in the namespace's modules. */
export function inNamespace(namespace: string, body: string, preamble = '') {
  const { open, close, indent } = openModules(namespace);

  const indented = body
    .trim()
    .split('\n')
    .map((line) => (line ? `${indent}${line}` : ''))
    .join('\n');

  return `${HEADER}${preamble ? `\n${preamble.trim()}\n` : ''}
${open}
${indented}
${close}
`;
}

/** A comment block, each line prefixed with `# `. */
const comment = (text: string) =>
  text
    .trim()
    .split('\n')
    .map((line) => `# ${line}`.trimEnd())
    .join('\n');

/** `my-elements` → `my/elements`, how Bundler requires a dashed gem name. */
export const gemRequirePath = (gemName: string) => gemName.replace(/-/g, '/');

export function libPaths(options: ResolvedOptions) {
  const ns = namespacePath(options.rubyNamespace);
  const entry = `lib/${gemRequirePath(options.gem.name)}.rb`;

  // A gem named after its namespace and framework (acme-ui-sinatra, with Acme::Ui) has its
  // entry point where the adapter would go (lib/acme/ui/sinatra.rb): the adapter moves aside.
  const adapter = (framework: string) => (entry === `lib/${ns}/${framework}.rb` ? `lib/${ns}/${framework}_adapter.rb` : `lib/${ns}/${framework}.rb`);

  return {
    ns,
    entry,
    version: `lib/${ns}/version.rb`,
    bundleHelper: `lib/${ns}/bundle_helper.rb`,
    configuration: `lib/${ns}/configuration.rb`,
    assets: `lib/${ns}/assets.rb`,
    formHelper: `lib/${ns}/form_helper.rb`,
    loader: `lib/${ns}/loader.rb`,
    viewContext: `lib/${ns}/view_context.rb`,
    foreignContext: `lib/${ns}/foreign_context.rb`,
    sinatra: adapter('sinatra'),
    bridgetown: adapter('bridgetown'),
    engine: `lib/${ns}/engine.rb`,
    gemspec: `${options.gem.name}.gemspec`,
  };
}

export function emitVersion(options: ResolvedOptions) {
  return inNamespace(
    options.rubyNamespace,
    `
# The npm package's version (${options.npmPackage}). The gem is released at the same version, so
# the server markup always matches the elements that upgrade it.
NPM_VERSION = ${rubyString(options.version)}

# RubyGems spells an npm prerelease differently: 0.2.0-next.0 is 0.2.0.pre.next.0.
VERSION = Gem::Version.new(NPM_VERSION).to_s
`,
  );
}

export function emitBundleHelper(options: ResolvedOptions) {
  const key = options.configKey;
  const { loader, stylesheet } = options.assets;

  const ns = options.rubyNamespace;
  const local = options.assets.source === 'local';
  // Turbo (turbo-rails) reloads the page when a tracked asset's URL changes; only the Rails gem can ask for it.
  const turbo = options.framework === 'rails';

  const body = `
# Loads the Stencil bundle the generated components render for: the lazy loader
# (${loader}) and the global stylesheet${stylesheet ? ` (${stylesheet})` : ''}, and preloads what
# the page's elements need (config.assets.async).
#
#   <%= ${key}_tags %>
#
# Where the files come from is config.assets.source:
#   :cdn    ${options.npmPackage} at this gem's version on the CDN (CDN_URL)${local ? '' : ', the default'}
#   :local  your own copy (LOCAL_URL)${local ? ', the default' : ''}: the npm package's lazy build
#           (node_modules/${options.npmPackage}/${options.assets.lazyDir ? '<its lazy directory>' : 'dist/<namespace>'}), copied or
#           linked into public/ at that path
# or any other URL, with config.assets.bundle_url. Either way the server markup and the elements
# match only while the files are this gem's version of the package.
# An app that bundles its JavaScript can import "${options.npmPackage}/loader" and call
# defineCustomElements() instead, and leave this helper out.
module BundleHelper
  CDN_URL = ${rubyString(options.assets.cdnUrl)}
  LOCAL_URL = ${rubyString(options.assets.localPath)}

  def self.bundle_url
    assets = ${ns}.config.assets
    (assets.bundle_url || format((assets.source == :local) ? LOCAL_URL : CDN_URL, version: NPM_VERSION)).to_s.chomp("/")
  end

  # The URL of a file whose name has no hash: the loader and the global stylesheet (every other
  # file's name is its hash). Unless the bundle's URL names the version, the build's digest goes
  # in the query, so a new build is a new URL and no browser or proxy serves the old file for it.
  def self.unhashed_url(file)
    base = bundle_url
    return "#{base}/#{file}" if base.include?(NPM_VERSION)

    "#{base}/#{file}?v=#{${ns}.manifest.dig("assets", "digest") || NPM_VERSION}"
  end

  # The configured design tokens as one <style> rule (config.tokens, config.token_selector), or nil.
  def self.token_css(config = ${ns}.config)
    return if config.tokens.empty?

    selector = config.token_selector.to_s
    return config.invalid!("token_selector #{selector.inspect} can't hold { } < >") if selector.match?(/[{}<>]/)

    "#{selector}{#{config.tokens.map { |name, value| "#{name}:#{value}" }.join(";")}}"
  end

  # The head's tags: the global stylesheet, the loader and the token style. With
  # config.assets.async, also a modulepreload per file the rendered elements (and
  # config.assets.always) need, and a prefetch per file config.assets.preload needs. Call it in the
  # layout's <head>: the page's body has rendered by then. Options go onto the script tag (nonce:, …).${
    turbo
      ? `
  # In an app with Turbo, the stylesheet and the loader are tracked (data-turbo-track="reload"),
  # so a page visited after a deploy that changed them reloads instead of keeping the old ones.`
      : ''
  }
  def ${key}_tags(**script_options)
    config = ${ns}.config
    files = ${ns}.manifest["assets"]
    assets = ${ns}::Assets
    registry = assets.current
    helper = ${ns}::BundleHelper
    preloads = []
    prefetches = []
    if config.assets.async
      preloads = assets.files_for(registry.tags | assets.tags_for(config.assets.always))
      prefetches = assets.files_for(assets.tags_for(config.assets.preload)) - preloads
    end
    css = helper.token_css${turbo ? '\n    track = defined?(::Turbo) ? {"data-turbo-track": "reload"} : {}' : ''}
    registry.emitted!
    safe_join([
      (tag.link(rel: "stylesheet", href: helper.unhashed_url(files["stylesheet"])${turbo ? ', **track' : ''}) if files["stylesheet"]),
      *preloads.map { |file| tag.link(rel: "modulepreload", href: "#{helper.bundle_url}/#{file}") },
      tag.script("", type: "module", src: helper.unhashed_url(files["loader"])${turbo ? ', **track' : ''}, **script_options),
      *prefetches.map { |file| tag.link(rel: "prefetch", as: "script", href: "#{helper.bundle_url}/#{file}") },
      # Token names are checked against the library's list and values can't hold ; { } < > or a
      # line break (Configuration::Tokens), so the rule is written as is: escaping would break
      # quoted values ("Inter").
      (tag.style(css.html_safe, nonce: script_options[:nonce]) if css) # rubocop:disable Rails/OutputSafety -- see above
    ].compact, "\\n")
  end
end
`;

  return inNamespace(options.rubyNamespace, body);
}

export function emitEngine(options: ResolvedOptions) {
  const key = options.configKey;
  const ns = options.rubyNamespace;
  const viewPath = namespacePath(ns);

  const body = `
# Loads the generated components and helpers into a Rails app:
# - ${ns}::*Component autoload from app/components (once: they are library
#   code, not reloaded with the app).
# - Every view gets ${options.helperPrefix}* (Helpers) and ${key}_tags (BundleHelper).
# - Every view gets ${key}_form_with and ${key}_form_for (FormHelper), with ${ns}::FormBuilder.
# - Every form builder gets f.${options.helperPrefix}* (FormBuilderMethods), unless
#   config.${key}.form_builder = false; with :default, ${ns}::FormBuilder is every form's builder.
# - previews/ joins ViewComponent's preview paths, so Lookbook (or /rails/view_components)
#   lists one preview per element, unless config.${key}.previews = false.
class Engine < ::Rails::Engine
  config.${key} = ActiveSupport::OrderedOptions.new
  config.${key}.form_builder = true
  config.${key}.previews = true
  config.${key}.bundle_url = nil
  config.${key}.source = nil

  config.autoload_once_paths << root.join("app/components").to_s
  config.autoload_once_paths << root.join("app/helpers").to_s

  # config.${key}.* (config/application.rb) goes into ${ns}.config; a configure
  # block in config/initializers runs after this and can change it.
  initializer "${key}.config" do |app|
    settings = app.config.${key}
    config = ${ns}.config
    config.environment = Rails.env.to_s
    config.logger = Rails.logger
    config.assets.bundle_url = settings.bundle_url if settings.bundle_url
    config.form_builder = settings.form_builder unless settings.form_builder.nil?
    config.assets.source = settings.source if settings.source
    %i[async always preload].each { |name| config.assets.public_send(:"#{name}=", settings[name]) if settings.key?(name) }
    config.token_selector = settings.token_selector if settings.token_selector
    settings.tokens&.each { |name, value| config.tokens[name] = value }
    settings.defaults&.each { |component, props| config.defaults[component] = props }
  end

  # A fresh asset registry for every request (and job) the executor runs.
  initializer "${key}.assets" do |app|
    app.executor.to_run { ${ns}::Assets.reset! }
    app.executor.to_complete { ${ns}::Assets.reset! }
  end

  initializer "${key}.helpers" do
    ActiveSupport.on_load(:action_view) do
      include ${ns}::Helpers
      include ${ns}::BundleHelper
      include ${ns}::FormHelper

      form_builder = ${ns}.config.form_builder
      ActionView::Helpers::FormBuilder.include(${ns}::FormBuilderMethods) if form_builder
      ActionView::Base.default_form_builder = ${ns}::FormBuilder if form_builder == :default
    end
  end

  # The partial flavor (app/views/${viewPath}/_<element>.html.erb), for templates ReActionView
  # keeps reactive. ReActionView serves slot requests only from the app's own view paths, so the
  # engine's joins them; Rails adds it as an engine view path either way.
  initializer "${key}.partials", before: "reactionview.slots" do |app|
    views = root.join("app/views").to_s
    app.config.paths["app/views"] << views unless app.config.paths["app/views"].to_a.include?(views)
  end

  initializer "${key}.previews", after: "view_component.set_configs", before: "view_component.set_autoload_paths" do |app|
    previews = app.config.view_component.previews
    path = root.join("previews").to_s

    if app.config.${key}.previews && previews.enabled && Dir.exist?(path) && previews.paths.exclude?(path)
      previews.paths << path
    end
  end
end
`;

  return inNamespace(ns, body, 'require "rails/engine"');
}

/** The constant the gem used to have, still naming the namespace (deprecated). */
function legacyConstant(options: ResolvedOptions) {
  const legacy = options.legacy;

  if (!legacy?.constant) return '';
  const parts = legacy.constant.split('::');
  const last = parts.pop() ?? '';

  const intro = comment(
    `The gem was ${legacy.gemName ?? 'renamed'}, with everything under ${legacy.constant}, before it was
${options.gem.name}. The old constant still resolves, for one release, and warns where
Ruby's deprecation warnings are on (Warning[:deprecated] = true, or ruby -W:deprecated).`,
  );

  if (parts.length === 0) return `\n${intro}\n${last} = ${options.rubyNamespace}\nObject.deprecate_constant :${last}\n`;
  const { open, close, indent } = openModules(parts.join('::'));

  return `\n${intro}\n${open}\n${indent}${last} = ${options.rubyNamespace}\n${indent}deprecate_constant :${last}\n${close}\n`;
}

const requirePath = (file: string) => file.slice('lib/'.length, -'.rb'.length);

export function emitEntry(options: ResolvedOptions) {
  const paths = libPaths(options);
  const ns = options.rubyNamespace;
  const parts = ns.split('::');
  const { open, close, indent } = openModules(parts.slice(0, -1).join('::') || parts[0]);
  const rails = options.framework === 'rails';

  const where = {
    rails: `the engine adds a ${options.helperPrefix}*\nhelper per element to every view`,
    sinatra: `register ${ns}::Sinatra adds a\n${options.helperPrefix}* helper per element to the app's templates`,
    bridgetown: `init :${options.gem.name} adds a\n${options.helperPrefix}* helper per element to the site's templates`,
  }[options.framework];

  const describe = comment(
    `One ViewComponent per ${options.npmPackage} web component, generated from the Stencil sources:
each element's ${parts.at(-1)}::*Component renders it, and ${where}. The browser half is
${options.npmPackage} at the same version; see ${options.configKey}_tags.`,
  )
    .split('\n')
    .map((line) => `${indent}${line}`)
    .join('\n');

  const moduleBlock =
    parts.length > 1
      ? `${open}\n${describe}\n${indent}module ${parts.at(-1)}\n${indent}end\n${close}`
      : `${describe.replace(/^ {2}/gm, '')}\nmodule ${ns}\nend`;

  const before = rails ? ['view_component'] : ['action_view', 'active_support', 'view_component'];

  const after = rails
    ? [paths.configuration, paths.assets, paths.bundleHelper, paths.formHelper, paths.engine]
    : [paths.foreignContext, paths.loader, paths.configuration, paths.assets, paths.bundleHelper, paths.formHelper, paths.viewContext, options.framework === 'sinatra' ? paths.sinatra : paths.bridgetown];

  return `${HEADER}
${before.map((lib) => `require "${lib}"`).join('\n')}
require "${requirePath(paths.version)}"

${moduleBlock}

${after.map((file) => `require "${requirePath(file)}"`).join('\n')}
${legacyConstant(options)}`;
}

/** lib/<old require path>.rb: the old entry point, kept for one release. */
export function emitLegacyRequire(options: ResolvedOptions) {
  const legacy = options.legacy;

  if (!legacy?.require) return undefined;
  const entry = gemRequirePath(options.gem.name);

  const message = `[${options.gem.name}] require ${JSON.stringify(legacy.require)} is deprecated; require ${JSON.stringify(entry)} (the gem's name is ${options.gem.name}, its module ${options.rubyNamespace})`;

  return [
    `lib/${legacy.require}.rb`,
    `${HEADER}
# The gem's entry point before it was renamed ${options.gem.name}, kept for one
# release: require ${JSON.stringify(entry)} instead.
warn ${rubyString(message)}, uplevel: 1

require ${rubyString(entry)}
`,
  ] as const;
}

export function emitGemspec(options: ResolvedOptions) {
  const { gem } = options;
  const paths = libPaths(options);

  const metadata = [
    gem.homepage ? `    "homepage_uri" => spec.homepage` : null,
    gem.homepage && gem.sourcePath ? `    "source_code_uri" => "#{spec.homepage}/tree/main/${gem.sourcePath}"` : null,
    gem.changelogUri ? `    "changelog_uri" => ${rubyString(gem.changelogUri)}` : null,
    `    "rubygems_mfa_required" => "true"`,
  ].filter(Boolean);

  const description = gem.description
    .trim()
    .split('\n')
    .map((line) => `    ${line}`.trimEnd())
    .join('\n');

  const dependencies = gemDependencies(options).map(({ name, requirements, note }) => `${note ? `${comment(note).replace(/^/gm, '  ')}\n` : ''}  spec.add_dependency ${[name, ...requirements].map(rubyString).join(', ')}`);

  return `${HEADER}
require_relative ${rubyString(paths.version.slice(0, -'.rb'.length))}

Gem::Specification.new do |spec|
  spec.name = ${rubyString(gem.name)}
  spec.version = ${options.rubyNamespace}::VERSION
  spec.authors = [${gem.authors.map(rubyString).join(', ')}]
  spec.summary = ${rubyString(gem.summary)}
  spec.description = <<~TEXT
${description}
  TEXT
${gem.homepage ? `  spec.homepage = ${rubyString(gem.homepage)}\n` : ''}  spec.license = ${rubyString(gem.license)}
  spec.required_ruby_version = ${rubyString(gem.requiredRubyVersion)}

  spec.metadata = {
${metadata.join(',\n')}
  }

  # The generated tree is committed, so a git or path source installs the same files as the
  # released gem.
  spec.files = Dir[
    "lib/**/*.{rb,json}",
    "app/components/**/*.{rb,erb}",
    "app/views/**/*.erb",
    "app/helpers/**/*.rb",
    "app/javascript/**/*.ts",
    "sig/**/*.rbs",
    "previews/**/*.rb",
${gem.extraFiles.map((file) => `    ${rubyString(file)}`).join(',\n')}
  ]
  spec.require_paths = ["lib"]

${dependencies.join('\n')}
end
`;
}

interface Dependency {
  name: string;
  requirements: string[];
  note?: string;
}

/** The gem's runtime dependencies, per framework. */
function gemDependencies(options: ResolvedOptions): Dependency[] {
  const optStruct = {
    name: 'opt_struct',
    requirements: ['>= 1.8', '< 2'],
    note: 'Props are OptStruct options. opt_struct (MIT, Carl Zulauf, https://github.com/carlzulauf/opt_struct).',
  };

  // ForeignContext overrides a private ViewComponent method (the slot setter), so outside Rails
  // the gem is pinned to the major version it was written against.
  const viewComponent = { name: 'view_component', requirements: ['>= 4.15', '< 5'] };

  const actionView = [
    { name: 'actionview', requirements: ['>= 8.1', '< 9'] },
    { name: 'activesupport', requirements: ['>= 8.1', '< 9'] },
  ];

  const zeitwerk = { name: 'zeitwerk', requirements: ['>= 2.6', '< 3'] };

  switch (options.framework) {
    case 'sinatra':
      return [
        { name: 'sinatra', requirements: ['>= 4', '< 5'] },
        { name: 'erubi', requirements: ['>= 1.13', '< 2'], note: 'Block helpers in Sinatra ERB need Erubi::CaptureBlockEngine (erubi 1.13).' },
        ...actionView,
        viewComponent,
        optStruct,
        zeitwerk,
      ];
    case 'bridgetown':
      return [{ name: 'bridgetown-core', requirements: ['>= 2', '< 3'] }, ...actionView, viewComponent, optStruct, zeitwerk];
    default:
      return [{ name: 'actionview', requirements: ['>= 8.1', '< 9'] }, { name: 'railties', requirements: ['>= 8.1', '< 9'] }, viewComponent, optStruct];
  }
}

/** Every lib/ file and the gemspec, keyed by path relative to the out dir. */
export function emitLib(options: ResolvedOptions): Map<string, string> {
  const paths = libPaths(options);
  const files = new Map<string, string>();

  files.set(paths.entry, emitEntry(options));
  files.set(paths.version, emitVersion(options));
  files.set(paths.bundleHelper, emitBundleHelper(options));

  if (options.framework === 'rails') files.set(paths.engine, emitEngine(options));
  const legacy = emitLegacyRequire(options);

  if (legacy) files.set(legacy[0], legacy[1]);
  files.set(paths.gemspec, emitGemspec(options));

  return files;
}
