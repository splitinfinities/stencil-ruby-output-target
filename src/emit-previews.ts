import type { ComponentModel, PropModel } from './model.ts';
import type { ResolvedOptions } from './options.ts';
import { rubyString } from './naming.ts';

/**
 * A ViewComponent preview per element (`previews/`), from the same model as the classes, with
 * Lookbook `@param` tags so each attribute gets a control: booleans are toggles, enums
 * selects, numbers number fields, everything else text. Props without an attribute (JSON
 * properties) and deprecated props get no control. The engine adds `previews/` to
 * ViewComponent's preview paths, so Lookbook and /rails/view_components list them.
 */

const HEADER = '# frozen_string_literal: true\n\n# Generated by stencil-ruby-output-target. Do not edit.\n';

/** Ruby keywords a parameter may be named but a local variable can't be read as. */
const KEYWORDS = new Set([
  'alias', 'and', 'begin', 'break', 'case', 'class', 'def', 'defined?', 'do', 'else', 'elsif', 'end', 'ensure',
  'false', 'for', 'if', 'in', 'module', 'next', 'nil', 'not', 'or', 'redo', 'rescue', 'retry', 'return', 'self',
  'super', 'then', 'true', 'undef', 'unless', 'until', 'when', 'while', 'yield', '__method__',
]);

/** The props a preview offers a control for. */
export function previewProps(component: ComponentModel): PropModel[] {
  return component.props.filter((prop) => prop.attribute && prop.kind !== 'json' && prop.deprecated === undefined);
}

function paramTag(prop: PropModel) {
  switch (prop.kind) {
    case 'boolean':
      return `# @param ${prop.key} [Boolean] toggle`;
    case 'number':
      return `# @param ${prop.key} number`;
    case 'enum': {
      // A blank choice for an enum without a default: the component's own default applies.
      const choices = [...(prop.rubyDefault === null || prop.rubyDefault === 'nil' ? [''] : []), ...(prop.values ?? [])];

      return `# @param ${prop.key} select { choices: [${choices.map((value) => rubyString(value)).join(', ')}] }`;
    }

    default:
      return `# @param ${prop.key} text`;
  }
}

/** The example's default for a prop: its own default, or a sample when it is required. */
function paramDefault(prop: PropModel) {
  if (prop.rubyDefault !== null && prop.rubyDefault !== 'nil' && !prop.rubyDefault.endsWith('.freeze')) return prop.rubyDefault;

  if (!prop.required) return 'nil';

  if (prop.kind === 'enum') return rubyString(prop.values?.[0] ?? '');

  if (prop.kind === 'number') return '0';

  if (prop.kind === 'boolean') return 'false';

  return rubyString('Example');
}

const read = (name: string) => (KEYWORDS.has(name) ? `binding.local_variable_get(:${name})` : name);

export function emitPreview(component: ComponentModel, options: ResolvedOptions) {
  const props = previewProps(component);
  const keys = new Set(component.props.map((prop) => prop.key));
  const hasContent = component.slots.some((slot) => slot.name === '');
  const contentParam = keys.has('content') ? 'slot_content' : 'content';
  const tags = props.map(paramTag);
  const params = props.map((prop) => `${prop.key}: ${paramDefault(prop)}`);

  if (hasContent) {
    tags.push(`# @param ${contentParam} text`);
    params.push(`${contentParam}: ${rubyString((component.tag.startsWith(options.tagPrefix) ? component.tag.slice(options.tagPrefix.length) : component.tag).replace(/-/g, ' '))}`);
  }

  const args = props.map((prop) => `${prop.key}: ${read(prop.key)}`);
  const indent = '  '.repeat(options.rubyNamespace.split('::').length);
  const hash = args.length ? `{\n${args.map((arg) => `      ${arg}`).join(',\n')}\n    }` : '{}';
  const block = hasContent ? ` { ${contentParam} }` : '';

  // No locals: any name could be a prop's.
  const body = [
    `# <${component.tag}> with a control per attribute. Blank values fall back to the component's defaults.`,
    `class ${component.className}Preview < ViewComponent::Preview`,
    ...tags.map((tag) => `  ${tag}`),
    params.length ? `  def default(${params.join(', ')})` : '  def default',
    `    render(${component.className}.new(**${hash}.reject { _2.nil? || _2 == "" }))${block}`,
    '  end',
    'end',
  ].flatMap((line) => line.split('\n'));

  const parts = options.rubyNamespace.split('::');

  return `${HEADER}
${parts.map((part, n) => `${'  '.repeat(n)}module ${part}`).join('\n')}
${body.map((line) => (line ? `${indent}${line}` : '')).join('\n')}
${parts.map((_, n) => `${'  '.repeat(parts.length - 1 - n)}end`).join('\n')}
`;
}
