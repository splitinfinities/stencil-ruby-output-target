import type { ComponentModel } from './model.ts';

const SAFE_DETAIL = /^(any|unknown|void|string|number|boolean|null|undefined|object|Record<string, (any|unknown|string|number|boolean)>|(string|number|boolean)\[\])$/;

/** One element's entry in the generated `STENCIL_ELEMENTS` manifest. */
interface ManifestEntry {
  model?: ComponentModel['model'];
  properties: string[];
  events: string[];
}

/** Metadata the runtime needs, plus a typed event map for TypeScript consumers. */
export function emitManifest(components: ComponentModel[]) {
  const manifest = Object.fromEntries(
    components.map((c) => {
      const spec: ManifestEntry = {
        properties: c.props.filter((p) => p.strategy === 'property' || p.list).map((p) => p.jsName),
        events: c.events.map((e) => e.dom),
      };

      if (c.model) spec.model = c.model;

      return [c.tag, spec];
    }),
  );

  const eventMap = components
    .flatMap((c) => c.events.map((e) => `  ${JSON.stringify(`${c.tag}:${e.dom}`)}: CustomEvent<${SAFE_DETAIL.test(e.detail) ? e.detail : 'unknown'}>;`))
    .join('\n');

  return `// Generated by stencil-ruby-output-target. Do not edit.

export interface ElementSpec {
  readonly model?: { readonly prop: string; readonly event: string };
  readonly properties: readonly string[];
  readonly events: readonly string[];
}

export const STENCIL_ELEMENTS: Readonly<Record<string, ElementSpec>> = ${JSON.stringify(manifest, null, 2)};

/** \`"<tag>:<event>"\` → event type, for typing listeners on generated elements. */
export interface StencilElementEventMap {
${eventMap}
}
`;
}
