import type { ComponentModel, PropModel } from './model.ts';
import type { ResolvedOptions } from './options.ts';
import { rubyString } from './naming.ts';

/**
 * RBS signatures (`sig/`) for the generated Ruby, from the same model as the classes:
 * each component's `initialize` keywords with their types, its readers, its slot methods,
 * and the helpers and FormBuilder methods that render it. Enums are unions of their
 * values as strings and symbols (the classes accept either); deprecated props carry
 * `%a{deprecated: …}`, which Steep reports at the call site.
 */

const HEADER = '# Generated by stencil-ruby-output-target. Do not edit.\n';

/** A state, field or attribute name. */
const NAME = '(String | Symbol)';

function openModules(namespace: string) {
  const parts = namespace.split('::');

  return {
    open: parts.map((part, i) => `${'  '.repeat(i)}module ${part}`).join('\n'),
    close: parts.map((_, i) => `${'  '.repeat(parts.length - 1 - i)}end`).join('\n'),
    indent: '  '.repeat(parts.length),
  };
}

/** A string or symbol literal type for an enum value. */
function literals(value: string) {
  return [rubyString(value), /^[a-z_][a-z0-9_]*$/i.test(value) ? `:${value}` : `:${rubyString(value)}`];
}

/** The type a caller may pass, without nil. */
export function rbsType(prop: PropModel): string {
  switch (prop.kind) {
    case 'boolean':
      return 'bool';
    case 'number':
      return 'Numeric';
    case 'json':
      return 'untyped';
    case 'enum': {
      const union = (prop.values ?? []).flatMap(literals).join(' | ');

      return prop.list ? `(${union} | Array[String])` : `(${union})`;
    }

    default:
      return prop.list ? '(String | Array[String])' : 'String';
  }
}

const nilable = (type: string) => (type === 'untyped' ? type : `${type}?`);

/** A deprecation annotation; RBS annotations can't hold braces or line breaks. */
const annotation = (text: string) => `%a{deprecated: ${text.replace(/[{}\n]/g, ' ').replace(/\s+/g, ' ').trim()}}`;

/** The keyword parameters of a component's `new` (and its helper). */
export function keywordParams(component: ComponentModel): string[] {
  const params = component.props.map((prop) => `${prop.required ? '' : '?'}${prop.key}: ${prop.required ? rbsType(prop) : nilable(rbsType(prop))}`);
  const keys = new Set(component.props.map((prop) => prop.key));

  // BaseComponent#initialize's binding keywords. A `state` prop keeps its name; the binding is then `client_state`.
  if (!keys.has('bind')) params.push(`?bind: ${NAME}?`);

  params.push(`?${keys.has('state') ? 'client_state' : 'state'}: ${NAME}?`);

  if (component.formField) {
    if (!keys.has('form')) params.push('?form: untyped');

    if (!keys.has('attribute')) params.push(`?attribute: ${NAME}?`);
  }

  params.push('**untyped html_attributes');

  return params;
}

function slotMethods(component: ComponentModel) {
  return component.slots.flatMap((slot) => {
    if (slot.name === '') return [];
    const name = slot.rubyName;

    if (slot.many) {
      const one = name.replace(/s$/, '');

      return [
        `def with_${one}: (*untyped, **untyped) ?{ (?) -> untyped } -> self`,
        `def with_${name}: (Array[untyped]) -> self`,
        `def ${name}: () -> Array[untyped]`,
        `def ${name}?: () -> bool`,
      ];
    }

    return [
      `def with_${name}: (*untyped, **untyped) ?{ (?) -> untyped } -> self`,
      `def with_${name}_content: (String) -> self`,
      `def ${name}: () -> untyped`,
      `def ${name}?: () -> bool`,
    ];
  });
}

export function emitComponentSignature(component: ComponentModel, options: ResolvedOptions) {
  const { open, close, indent } = openModules(options.rubyNamespace);
  const lines: string[] = [];

  lines.push(`def initialize: (${keywordParams(component).join(', ')}) -> void`, '');

  for (const prop of component.props) {
    const summary = prop.docs.split('\n')[0]?.trim();

    if (summary) lines.push(`# ${summary}`);

    if (prop.deprecated !== undefined) lines.push(annotation(prop.deprecated || 'deprecated'));

    lines.push(`def ${prop.reader}: () -> ${prop.rubyDefault !== null && prop.rubyDefault !== 'nil' ? rbsType(prop) : nilable(rbsType(prop))}`);
  }

  const slots = slotMethods(component);

  if (slots.length) lines.push('', ...slots);

  const body = lines.map((line) => (line ? `${indent}  ${line}` : '')).join('\n');

  return `${HEADER}
${open}
${indent}# Renders <${component.tag}>. Helper: ${component.helper}(...)
${indent}class ${component.className} < BaseComponent
${body}
${indent}end
${close}
`;
}

export function emitBaseSignature(options: ResolvedOptions) {
  const { open, close, indent } = openModules(options.rubyNamespace);

  const body = `# Shared behaviour for every generated element component.
class BaseComponent < ViewComponent::Base
  type prop_spec = { type: Symbol, js: String, attribute: String?, values: Array[String]?, default: untyped, strategy: Symbol, reader: Symbol, required: bool, list: bool, reactive: bool }

  PROTECTED_OWNERS: Array[Module]
  TIME_FORMATS: Hash[String, String]

  def self.element_tag: () -> String
  def self.element_tag=: (String) -> String
  def self.model: () -> { prop: String, event: String }?
  def self.model=: ({ prop: String, event: String }?) -> { prop: String, event: String }?
  def self.props: () -> Hash[Symbol, prop_spec]
  def self.props=: (Hash[Symbol, prop_spec]) -> Hash[Symbol, prop_spec]
  def self.events: () -> Hash[Symbol, String]
  def self.events=: (Hash[Symbol, String]) -> Hash[Symbol, String]
  def self.form_field: () -> Hash[Symbol, Symbol]?
  def self.form_field=: (Hash[Symbol, Symbol]?) -> Hash[Symbol, Symbol]?

  def self.prop: (Symbol key, type: Symbol, js: String, strategy: Symbol, ?attribute: String?, ?values: Array[String]?, ?default: untyped, ?reader: Symbol, ?required: bool, ?list: bool, ?reactive: bool) -> void
  def self.event: (Symbol key, dom: String) -> void
  # OptStruct's: every option's key (the props').
  def self.defined_keys: () -> Array[Symbol]
  def self.form_options: (untyped form, ${NAME} attribute, ?Hash[Symbol, untyped] options) -> Hash[Symbol, untyped]
  def self.human_attribute_name: (untyped object, ${NAME} attribute) -> String
  def self.checkable?: (Hash[Symbol, untyped] options) -> bool
  def self.radio?: (Hash[Symbol, untyped] options) -> bool
  def self.checked_value?: (untyped raw, untyped on, bool radio) -> bool
  def self.form_value: (untyped raw, ${NAME} kind) -> untyped

  def initialize: (**untyped kwargs) -> void

  # OptStruct's: every keyword given to new, the props' defaults filled in.
  attr_reader options: Hash[Symbol, untyped]

  def attribute?: (Symbol key) -> bool
  def attribute_value: (Symbol key) -> String
  def reactive_value: (Symbol key) -> String
  def host_attributes: () -> Hash[Symbol, untyped]
  def property_payload: () -> String
  def slotted: (String name, untyped html) -> String
  def host_id: () -> String
  def host_class: () -> String
  def server_binding: () -> String
  def herb_set: () -> String
  def client_binding: () -> String
  def host_attribute_payload: () -> String

  private

  def html_attributes: () -> Hash[Symbol, untyped]
end`;

  return `${HEADER}
${open}
${body
  .split('\n')
  .map((line) => (line ? `${indent}${line}` : ''))
  .join('\n')}
${close}
`;
}

export function emitHelpersSignature(components: ComponentModel[], options: ResolvedOptions) {
  const { open, close, indent } = openModules(options.rubyNamespace);

  const methods = components.map(
    (c) => `${indent}  def ${c.helper}: (${keywordParams(c).join(', ')}) ?{ (${c.className}) -> untyped } -> String`,
  );

  const builder = components.flatMap((c) => {
    if (!c.formField) return [];

    const params = keywordParams(c)
      .filter((param) => !/^\?(form|attribute): /.test(param))
      .join(', ');

    return [`${indent}  def ${c.helper}: (${NAME} attribute, ${params}) ?{ (${c.className}) -> untyped } -> String`];
  });

  return `${HEADER}
${open}
${indent}# One helper per element; the engine includes it in every view.
${indent}module Helpers
${methods.join('\n')}
${indent}end

${indent}# f.${components.find((c) => c.formField)?.helper ?? `${options.helperPrefix}input`} :attribute, for each form-associated element.
${indent}module FormBuilderMethods
${builder.join('\n')}
${indent}end
${close}
`;
}
